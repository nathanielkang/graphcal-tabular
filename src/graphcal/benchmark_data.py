"""Pinned benchmark identities; no silent replacement dataset or target.

Raw caches are generated by scripts/prepare_revision_data.py. They carry source
identifiers and hashes; preprocessing is deferred until after sample splitting.
"""
from __future__ import annotations
from pathlib import Path
import json
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
MAIN_DATASETS = ('abalone','california','bike','wine','energy','airfoil',
                 'superconductor','cpu','forest_fires')
RESERVE_DATASETS = ('concrete','yacht','auto_mpg')


def cached_dataset_names() -> tuple[str, ...]:
    root = ROOT / 'data' / 'revision_cache'
    names = sorted(
        p.name[: -len('_meta.json')]
        for p in root.glob('*_meta.json')
        if not p.name.endswith('_openml_meta.json')
    )
    return tuple(names)


def load_revision_dataset(name: str):
    if name not in cached_dataset_names():
        raise ValueError(f'Unknown dataset: {name}')
    root = ROOT/'data'/'revision_cache'
    meta = json.loads((root/(name+'_meta.json')).read_text(encoding='utf-8'))
    frame = pd.read_pickle(root/(name+'.pkl'))
    # OpenML frames may leave category/object columns as Categorical; some pandas
    # paths used in TrainingEncoder raise NotImplementedError on raw Categorical.
    for col in list(frame.columns):
        if col == meta['target']:
            continue
        if isinstance(frame[col].dtype, pd.CategoricalDtype) or frame[col].dtype == object:
            frame[col] = frame[col].astype('string')
    y = pd.to_numeric(frame.pop(meta['target']), errors='raise').to_numpy(dtype=float)
    if not np.isfinite(y).all():
        raise ValueError('Non-finite benchmark target')
    if name == 'energy':
        # y2 is the removed second response. It is not an eighth-plus input.
        if 'y2' in frame.columns:
            raise ValueError('Energy still contains y2; refuse the old nine-input design')
        if frame.shape[1] != 8 or int(meta.get('d', -1)) != 8:
            raise ValueError('Energy must have eight predictors after y2 is removed')
        meta = dict(meta)
        meta['categorical'] = [c for c in meta.get('categorical', []) if c != 'y2' and c in frame.columns]
    return frame, y, meta
